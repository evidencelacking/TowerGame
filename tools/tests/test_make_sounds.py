import re
import struct
import sys
import tempfile
import unittest
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
sys.path[:0] = [str(ROOT / "tools")]

import make_sounds  # noqa: E402

CATALOG = (ROOT / "scripts" / "view" / "sound" / "sound_catalog.gd").read_text(encoding="utf-8")


def catalog_names():
    names = []
    for block in ("AMBIENCE_NAMES", "EVENT_NAMES"):
        body = re.search(block + r": Array\[String\] = \[(.*?)\n\]", CATALOG, re.S).group(1)
        names += re.findall(r'"([^"]+)"', body)
    return names


def samples(name):
    pcm = make_sounds.render(name)
    return struct.unpack("<%dh" % (len(pcm) // 2), pcm)


class MakeSounds(unittest.TestCase):
    def test_every_catalog_name_has_a_recipe(self):
        names = catalog_names()
        self.assertEqual(len(names), 58)
        self.assertEqual([n for n in names if n not in make_sounds.RECIPES], [])
        self.assertEqual(sorted(make_sounds.RECIPES), sorted(names))

    def test_output_is_deterministic(self):
        for name in make_sounds.RECIPES:
            self.assertEqual(make_sounds.wav_bytes(name), make_sounds.wav_bytes(name), name)

    def test_format_length_size_and_sources(self):
        with tempfile.TemporaryDirectory() as tmp:
            make_sounds.main(["make_sounds.py", tmp])
            total = 0
            sources = (Path(tmp) / "SOURCES.md").read_text(encoding="utf-8")
            for name in catalog_names():
                path = Path(tmp) / f"{name}.wav"
                total += path.stat().st_size
                with wave.open(str(path)) as w:
                    self.assertEqual((w.getnchannels(), w.getsampwidth(), w.getframerate()), (1, 2, 22050), name)
                    sec = w.getnframes() / 22050
                if name in make_sounds.LOOPS:
                    self.assertTrue(2.0 <= sec <= 4.0, f"{name} loop is {sec}s")
                else:
                    self.assertTrue(0.05 < sec < 1.5, f"{name} one-shot is {sec}s")
                self.assertIn(f"| {name}.wav | generated by tools/make_sounds.py", sources)
            self.assertLess(total, 3_100_000)

    def test_loops_join_without_a_click(self):
        # The jump from the last sample back to the first must be no bigger than the largest step
        # already inside the file, otherwise the loop point would be audible as a click.
        for name in sorted(make_sounds.LOOPS):
            s = samples(name)
            biggest = max(abs(b - a) for a, b in zip(s, s[1:]))
            self.assertLessEqual(abs(s[0] - s[-1]), biggest, name)


if __name__ == "__main__":
    unittest.main()
